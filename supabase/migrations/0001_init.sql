-- bump updated_at on session/template updates
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

drop trigger if exists trg_sessions_touch on public.sessions;
create trigger trg_sessions_touch before update on public.sessions
  for each row execute function public.touch_updated_at();

drop trigger if exists trg_templates_touch on public.templates;
create trigger trg_templates_touch before update on public.templates
  for each row execute function public.touch_updated_at();

-- auto-create a public.users row + personal org on signup
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  new_org_id uuid;
  base_slug  text;
begin
  base_slug := lower(regexp_replace(split_part(new.email, '@', 1), '[^a-z0-9]+', '-', 'g'))
               || '-' || substr(new.id::text, 1, 6);

  insert into public.organizations (name, slug)
  values (split_part(new.email, '@', 1) || '''s workspace', base_slug)
  returning id into new_org_id;

  insert into public.users (id, email, display_name, default_org_id)
  values (new.id, new.email, split_part(new.email, '@', 1), new_org_id);

  insert into public.memberships (user_id, org_id, role)
  values (new.id, new_org_id, 'owner');

  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
